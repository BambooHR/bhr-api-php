#!/usr/bin/env php
<?php
/**
 * sync_accessors.php — keep ApiClient's convenience accessors in sync with
 * the generated API classes.
 *
 * Background
 * ----------
 * `lib/Client/ApiClient.php` is hand-written, but a block of it is pure
 * boilerplate: one accessor per generated API class. That block used to be
 * maintained by hand, which meant the SDK silently broke whenever the
 * upstream spec renamed a tag.
 *
 * That is not hypothetical. The spec renamed `Tabular Data` -> `Employee
 * Tables` and `Last Change Information` -> `Change Tracking`. The generator
 * correctly produced EmployeeTablesApi / ChangeTrackingApi, the
 * obsolete-file cleanup correctly deleted the old classes, and the
 * hand-written accessors were left returning types that no longer existed.
 * PHPStan failed with "Class BhrSdk\Api\TabularDataApi not found" on code
 * nobody had touched. The same spec also added ~15 brand-new tags that got
 * no accessors at all, because adding them was a manual step somebody had
 * to remember.
 *
 * So the accessor block is now generated from the one source of truth the
 * generator itself maintains: the `lib/Api/*.php` entries in
 * `.openapi-generator/FILES`.
 *
 * Why FILES and not a glob of lib/Api/
 * ------------------------------------
 * `ManualApi.php` lives in `lib/Api/` but is hand-written and preserved
 * across regeneration. It is deliberately absent from the FILES manifest,
 * so reading the manifest gives exactly the generated classes and excludes
 * the hand-written one. A directory glob would sweep ManualApi in and
 * clobber its hand-written accessor.
 *
 * Preserving hand-written code
 * ----------------------------
 * This script only ever rewrites the text *between* two marker comments:
 *
 *     // --- BEGIN GENERATED ACCESSORS ---
 *     // --- END GENERATED ACCESSORS ---
 *
 * Everything outside those markers is byte-for-byte untouched. That is the
 * whole safety property. `manual()` is the live example: it sits below the
 * END marker where this script cannot reach it.
 *
 * If the markers are missing, the script refuses to do anything rather than
 * guessing where the block belongs.
 *
 * Usage
 * -----
 *     php scripts/sync_accessors.php            # rewrite the block in place
 *     php scripts/sync_accessors.php --check    # exit 1 if out of sync (CI)
 *     php scripts/sync_accessors.php --diff     # show what would change
 */

declare(strict_types=1);

const PROJECT_ROOT = __DIR__ . '/..';
const FILES_MANIFEST = PROJECT_ROOT . '/.openapi-generator/FILES';
const CLIENT_FILE = PROJECT_ROOT . '/lib/Client/ApiClient.php';

const BEGIN_MARKER = "\t// --- BEGIN GENERATED ACCESSORS ---";
const END_MARKER = "\t// --- END GENERATED ACCESSORS ---";

/**
 * Method names on ApiClient that a generated accessor must never shadow.
 *
 * If the spec ever grows a tag that collides with one of these, we want a
 * loud failure here rather than an accessor quietly clobbering build() or
 * getConfiguration().
 */
const RESERVED_NAMES = [
	'build',
	'getApi',
	'getAuthBuilder',
	'getConfiguration',
	'getLastRequestId',
	'getLogger',
	'getRefreshProvider',
	'getSanitizedAuthInfo',
	'getTokenManager',
	'manual',
	'onTokenRefresh',
	'forCompany',
	'withApiKey',
	'withDebug',
	'withHeaderSelector',
	'withHost',
	'withHostIndex',
	'withHttpClient',
	'withLogging',
	'withOAuth',
	'withOAuthRefresh',
	'withRetries',
];

/**
 * Read the generator's FILES manifest and return the generated API class names.
 *
 * @return string[] Class names (e.g. "EmployeeTablesApi"), sorted.
 */
function discoverApis(string $manifestPath): array {
	if (!is_file($manifestPath)) {
		throw new RuntimeException("generated FILES manifest not found: {$manifestPath}");
	}

	$classes = [];
	foreach (explode("\n", (string) file_get_contents($manifestPath)) as $line) {
		if (preg_match('#^lib/Api/(\w+)\.php$#', trim($line), $matches) === 1) {
			$classes[] = $matches[1];
		}
	}

	if ($classes === []) {
		throw new RuntimeException(
			"no lib/Api/*.php entries found in {$manifestPath}. Has the generator run?"
		);
	}

	$classes = array_values(array_unique($classes));
	sort($classes);

	return $classes;
}

/**
 * Derive the accessor method name from an API class name.
 *
 * "EmployeeTablesApi" -> "employeeTables".
 */
function methodNameFor(string $class): string {
	$stem = preg_replace('/Api$/', '', $class) ?? $class;

	return lcfirst($stem);
}

/**
 * Render the full generated accessor block, markers included.
 *
 * @param string[] $classes
 */
function renderBlock(array $classes): string {
	$lines = [
		BEGIN_MARKER,
		"\t// Generated by scripts/sync_accessors.php from .openapi-generator/FILES.",
		"\t// Do not edit by hand — run `make sync-accessors` instead. Hand-written",
		"\t// accessors (e.g. manual()) belong BELOW the END marker.",
	];

	$seen = [];
	foreach ($classes as $class) {
		$name = methodNameFor($class);

		if (in_array($name, RESERVED_NAMES, true)) {
			throw new RuntimeException(
				"generated accessor {$name}() for {$class} collides with an existing "
				. 'ApiClient member. Rename the spec tag, or add an explicit mapping '
				. 'in scripts/sync_accessors.php.'
			);
		}
		if (isset($seen[$name])) {
			throw new RuntimeException(
				"generated accessor name {$name} produced by both {$seen[$name]} and {$class}."
			);
		}
		$seen[$name] = $class;

		$lines[] = '';
		$lines[] = "\t/**";
		$lines[] = "\t * Convenience method to get {$class} instance";
		$lines[] = "\t *";
		$lines[] = "\t * @return \\BhrSdk\\Api\\{$class}";
		$lines[] = "\t */";
		$lines[] = "\tpublic function {$name}(): \\BhrSdk\\Api\\{$class} {";
		$lines[] = "\t\treturn \$this->getApi(\\BhrSdk\\Api\\{$class}::class);";
		$lines[] = "\t}";
	}

	$lines[] = '';
	$lines[] = END_MARKER;
	$lines[] = '';

	return implode("\n", $lines);
}

/**
 * Splice a rendered block into the client source, replacing everything
 * between the markers. Only the marked region is touched.
 */
function applyBlock(string $source, string $block): string {
	foreach ([[BEGIN_MARKER, 'BEGIN'], [END_MARKER, 'END']] as [$marker, $label]) {
		$count = substr_count($source, $marker);
		if ($count === 0) {
			throw new RuntimeException(
				"{$label} marker not found in ApiClient.php. Add these lines around the "
				. "convenience accessors:\n" . BEGIN_MARKER . "\n" . END_MARKER
			);
		}
		if ($count > 1) {
			throw new RuntimeException(
				"{$label} marker appears {$count} times in ApiClient.php; expected exactly one."
			);
		}
	}

	$start = strpos($source, BEGIN_MARKER);
	$end = strpos($source, END_MARKER);
	if ($start === false || $end === false || $end < $start) {
		throw new RuntimeException('END marker precedes BEGIN marker in ApiClient.php.');
	}

	return substr($source, 0, $start) . $block . substr($source, $end + strlen(END_MARKER) + 1);
}

// ---------------------------------------------------------------------------

$checkOnly = in_array('--check', $argv, true);
$showDiff = in_array('--diff', $argv, true);

try {
	$classes = discoverApis(FILES_MANIFEST);
	$current = (string) file_get_contents(CLIENT_FILE);
	$updated = applyBlock($current, renderBlock($classes));
} catch (RuntimeException $syncException) {
	fwrite(STDERR, 'sync_accessors: ' . $syncException->getMessage() . "\n");
	exit(2);
}

$count = count($classes);

if ($current === $updated) {
	echo "sync_accessors: up to date ({$count} generated accessors).\n";
	exit(0);
}

if ($showDiff) {
	$tmpCurrent = tempnam(sys_get_temp_dir(), 'acc_cur_');
	$tmpUpdated = tempnam(sys_get_temp_dir(), 'acc_new_');
	file_put_contents($tmpCurrent, $current);
	file_put_contents($tmpUpdated, $updated);
	passthru(sprintf('diff -u %s %s', escapeshellarg($tmpCurrent), escapeshellarg($tmpUpdated)));
	unlink($tmpCurrent);
	unlink($tmpUpdated);
}

if ($checkOnly) {
	fwrite(
		STDERR,
		"sync_accessors: accessors are OUT OF SYNC with the generated APIs. "
		. "Run `make sync-accessors` and commit the result.\n"
	);
	exit(1);
}

// --diff is a preview: report what would change, but never touch the file.
if ($showDiff) {
	echo "sync_accessors: --diff is read-only; re-run without it to apply.\n";
	exit(0);
}

file_put_contents(CLIENT_FILE, $updated);
echo "sync_accessors: rewrote {$count} generated accessors in lib/Client/ApiClient.php.\n";
exit(0);
